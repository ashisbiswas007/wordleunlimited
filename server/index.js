import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { readFile } from "node:fs/promises";

import Fastify from "fastify";
import fastifyStatic from "@fastify/static";
import fastifyCompress from "@fastify/compress";
import fastifyHelmet from "@fastify/helmet";
import fastifyCookie from "@fastify/cookie";
import fastifyRateLimit from "@fastify/rate-limit";
import fastifyWebsocket from "@fastify/websocket";

import config from "./config.js";
import { migrate } from "./db/migrate.js";
import { closePool, isDbAvailable, isDbEnabled } from "./db/pool.js";
import {
  loadSettings,
  getSettings,
  isMaintenance,
  startSettingsReloader,
  stopSettingsReloader,
} from "./lib/settings.js";

import registerApiRoutes from "./routes/api.js";
import registerAdminRoutes from "./routes/admin.js";
import registerPageRoutes from "./routes/pages.js";
import { registerRealtime, shutdownRealtime } from "./realtime/hub.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const PUBLIC_DIR = join(ROOT, "public");

/* Build-time CSP hashes for the inline <script> blocks (page config + JSON-LD).
   Generated by scripts/build-assets.mjs. Falling back to 'unsafe-inline' keeps
   `npm run dev` working before the first build. */
async function loadCspScriptSources() {
  try {
    const raw = await readFile(join(HERE, "generated", "csp-hashes.json"), "utf8");
    const hashes = JSON.parse(raw);
    if (Array.isArray(hashes) && hashes.length) return hashes;
  } catch {
    /* not built yet */
  }
  if (config.isProd) {
    console.warn(
      "[csp] no build-time script hashes found — falling back to 'unsafe-inline'. " +
        "Run `npm run assets` during the image build to tighten this."
    );
  }
  return ["'unsafe-inline'"];
}

export async function build() {
  const app = Fastify({
    logger: config.isProd
      ? { level: "warn" }
      : { level: "info", transport: undefined },
    trustProxy: config.trustProxy,
    // Static file serving dominates; keep per-request bookkeeping minimal.
    // A trailing slash is a different URL to Google, so it must not be folded.
    routerOptions: { ignoreTrailingSlash: false },
    bodyLimit: 256 * 1024,
  });

  const scriptSrc = await loadCspScriptSources();

  await app.register(fastifyHelmet, {
    contentSecurityPolicy: {
      directives: {
        defaultSrc: ["'self'"],
        baseUri: ["'self'"],
        frameAncestors: ["'self'"],
        objectSrc: ["'none'"],
        formAction: ["'self'"],
        // The game sets inline style attributes (tile sizing, animation delays,
        // progress bar widths), so style hashing is not workable here.
        styleSrc: ["'self'", "'unsafe-inline'"],
        scriptSrc: ["'self'", "https://accounts.google.com", ...scriptSrc],
        scriptSrcAttr: ["'none'"],
        imgSrc: ["'self'", "data:", "https://lh3.googleusercontent.com"],
        fontSrc: ["'self'", "data:"],
        // Drive appData save/load + Google Identity token endpoint.
        connectSrc: [
          "'self'",
          "https://www.googleapis.com",
          "https://accounts.google.com",
          "https://oauth2.googleapis.com",
          config.siteUrl.replace(/^http/, "ws"),
        ],
        frameSrc: ["https://accounts.google.com"],
        upgradeInsecureRequests: config.isProd ? [] : null,
      },
    },
    crossOriginEmbedderPolicy: false,
    // Google Identity Services opens a popup that needs to talk back to us.
    crossOriginOpenerPolicy: { policy: "same-origin-allow-popups" },
    hsts: config.isProd
      ? { maxAge: 31_536_000, includeSubDomains: true, preload: true }
      : false,
    referrerPolicy: { policy: "strict-origin-when-cross-origin" },
  });

  await app.register(fastifyCookie, { secret: config.sessionSecret });

  // Static assets ship pre-brotlied, so compression only ever runs on JSON.
  await app.register(fastifyCompress, {
    global: false,
    encodings: ["br", "gzip"],
    threshold: 1024,
  });

  await app.register(fastifyRateLimit, {
    global: false,
    max: 120,
    timeWindow: "1 minute",
    // Behind Traefik, req.ip is already the real client because trustProxy is on.
    keyGenerator: (req) => req.ip,
  });

  await app.register(fastifyWebsocket, {
    options: {
      maxPayload: 16 * 1024,
      clientTracking: false,
      // Room traffic is small JSON frames; per-message deflate costs more CPU
      // than it saves and is the single biggest ws memory sink.
      perMessageDeflate: false,
    },
  });

  /* ---------- maintenance gate ---------- */
  app.addHook("onRequest", async (req, reply) => {
    if (!isMaintenance()) return;

    const url = req.raw.url || "";
    // Admin must stay reachable to turn maintenance back off.
    if (
      url.startsWith("/admin") ||
      url.startsWith("/healthz") ||
      url.startsWith("/src/") ||
      url.startsWith("/api/status")
    ) {
      return;
    }

    const s = getSettings();
    reply.code(503).header("Retry-After", "300");

    if (url.startsWith("/api/") || url.startsWith("/ws")) {
      return reply.send({ error: "maintenance", message: s.maintenanceMessage });
    }

    reply.type("text/html; charset=utf-8");
    return reply.send(maintenancePage(s.maintenanceMessage));
  });

  /* ---------- health ---------- */
  app.get("/healthz", { logLevel: "silent" }, async () => ({
    ok: true,
    uptime: Math.round(process.uptime()),
    db: isDbEnabled() ? (isDbAvailable() ? "up" : "down") : "disabled",
  }));

  /* ---------- application routes (registered before static) ---------- */
  await app.register(registerApiRoutes, { prefix: "/api" });
  await app.register(registerAdminRoutes, { prefix: "/admin" });
  await registerRealtime(app);
  await app.register(registerPageRoutes);

  /* ---------- static ---------- */
  await app.register(fastifyStatic, {
    root: PUBLIC_DIR,
    index: ["index.html"],
    // Serves the .br / .gz sibling written at build time when the client
    // accepts it, so the CPU cost of compression is paid once, not per request.
    preCompressed: true,
    wildcard: false,
    etag: true,
    lastModified: true,
    cacheControl: false, // set per-type below
    setHeaders(res, path) {
      if (/\.(?:js|css|txt|json|woff2?|png|jpe?g|svg|webp|ico)$/i.test(path)) {
        // Assets are requested with a ?v=<build> cache buster from the HTML,
        // so they can be treated as permanently immutable.
        res.setHeader("Cache-Control", "public, max-age=31536000, immutable");
      } else if (/\.html$/i.test(path)) {
        res.setHeader("Cache-Control", "public, max-age=0, must-revalidate");
      } else if (/\.(?:xml|webmanifest)$/i.test(path)) {
        res.setHeader("Cache-Control", "public, max-age=3600");
      } else {
        res.setHeader("Cache-Control", "public, max-age=300");
      }
    },
  });

  app.setNotFoundHandler(
    { preHandler: app.rateLimit({ max: 60, timeWindow: "1 minute" }) },
    async (req, reply) => {
      if ((req.raw.url || "").startsWith("/api/")) {
        return reply.code(404).send({ error: "not_found" });
      }
      reply.code(404).type("text/html; charset=utf-8");
      return notFoundPage();
    }
  );

  return app;
}

