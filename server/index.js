function maintenancePage(message) {
  return shell(
    "Back shortly — Wordle Unlimited",
    `<div class="t"><i style="background:#6aaa64">W</i><i style="background:#c9b458">U</i><i style="background:#787c7e">!</i></div>
<h1>Back in a few minutes</h1><p>${escapeHtml(message)}</p>`
  );
}

function notFoundPage() {
  return shell(
    "Page not found — Wordle Unlimited",
    `<div class="t"><i style="background:#787c7e">4</i><i style="background:#c9b458">0</i><i style="background:#787c7e">4</i></div>
<h1>That page is missing</h1><p>The link may be old or mistyped.</p>
<a href="/">Play Wordle Unlimited</a>`
  );
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]
  );
}

/* ---------- boot ---------- */
async function start() {
  // A DB that is not ready yet must not stop the game from serving.
  try {
    await migrate();
  } catch (err) {
    console.error("[boot] migration failed:", err.message);
  }
  await loadSettings();
  startSettingsReloader();

  const app = await build();

  try {
    await app.listen({ port: config.port, host: config.host });
    console.log(
      `[boot] wordleunlimited listening on ${config.host}:${config.port} ` +
        `(${config.env}, db ${isDbEnabled() ? "configured" : "disabled"})`
    );
  } catch (err) {
    console.error("[boot] listen failed:", err);
    process.exit(1);
  }

  let closing = false;
  const shutdown = async (signal) => {
    if (closing) return;
    closing = true;
    console.log(`[shutdown] ${signal} received, draining…`);
    stopSettingsReloader();
    shutdownRealtime();
    // Give in-flight requests and websocket close frames a moment to land.
    const force = setTimeout(() => process.exit(1), 10_000);
    force.unref();
    await app.close().catch(() => {});
    await closePool();
    clearTimeout(force);
    process.exit(0);
  };

  process.on("SIGTERM", () => shutdown("SIGTERM"));
  process.on("SIGINT", () => shutdown("SIGINT"));
  process.on("unhandledRejection", (err) => {
    console.error("[fatal] unhandled rejection:", err);
  });
}

const invokedDirectly =
  process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (invokedDirectly) start();
